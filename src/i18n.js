let lang = 'en';
let currentPatientName = 'Mrs. Adebayo';
export function setLang(l) { lang = STR[l] ? l : 'en'; }
export function getLang() { return lang; }
export function setPatientName(name) { if (name) currentPatientName = name; }
export function t(key, params) {
  let s = STR[lang][key] ?? STR.en[key] ?? key;
  if (params) for (const k in params) s = s.replaceAll(`{${k}}`, params[k]);
  if (currentPatientName && currentPatientName !== 'Mrs. Adebayo') {
    s = s.replaceAll('Mrs. Adebayo:', `${currentPatientName}:`);
  }
  return s;
}
